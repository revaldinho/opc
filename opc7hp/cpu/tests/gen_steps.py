#!/usr/bin/env python3
'''
gen_steps.py - write haz_steps.s, the pipeline test of mulstep and divstep (added 13/11/2026)

  mulstep rd, rs, imm   rd := rd<<1 + (C ? rs+imm : 0); C kept
  divstep rd, rs, imm   t := rd<<1 | C (33 bits); t >= rs+imm: rd := t-(rs+imm), C := 1; else rd := t, C := 0

Like the hazard tests (gen_hazards.py) it is checked by comparing the CPU's retirement trace with
opc7emu.py (make hazards, make waits); ../../../opc7/tests/steps.s checks the arithmetic itself.
It has, from a fixed seed:
  - single steps with random and extreme operands, imm 0 and not, C 0 and 1 before them, their rd and
    rs written 1-3 instructions earlier (forwarding), rd and rs the same register, the source read
    with an imm (in EA: an interlock), the flags read back with getpsr, and predicated steps that
    pass and fail
  - full 32-bit multiplies (32 x add m,m; mulstep p,b, back to back) and full unsigned divides
    (32 x rol n,n; divstep r,d), their results stored
'''
import os, random

def main():
    random.seed(13112026)
    L = []
    e = L.append
    def const(r, v):
        v &= 0xFFFFFFFF
        lo, hi = v & 0xFFFF, v >> 16
        e("        mov     r%d, r0, %d" % (r, lo - 0x10000 if lo >= 0x8000 else lo))
        e("        movt    r%d, r0, %d" % (r, hi - 0x10000 if hi >= 0x8000 else hi))
    e("        # haz_steps.s: mulstep and divstep in the pipeline - generated by gen_steps.py, do not edit")
    e("")
    e("        # clear r1-r14 first: ALU instructions read their destination")
    for r in range(1, 15):
        e("        mov     r%d, r0, 0" % r)
    vals = [0, 1, -1, 2, 3, 7, 10, 100, 0x7FFFFFFF, -0x80000000, 0xFFFF, 12345, -54321, 0x12345678,
            0x80000001] + [random.randint(-2**31, 2**31 - 1) for _ in range(15)]
    e("")
    e("        # single steps")
    for i in range(120):
        a, b = random.choice(vals), random.choice(vals)
        const(1, a)
        const(2, b)
        for _ in range(random.choice([0, 1, 2])):
            e("        add     r9, r0, 1")
        imm = random.choice([0, 0, 1, -1, 100, -1000])
        e("        " + random.choice(["add     r0, r0", "cmp     r0, r0"]))   # C := 0 or 1
        k = random.choice(["mulstep", "divstep"])
        e("        %s r1, r2, %d" % (k, imm))
        e("        sto     r1, r0, res")
        e("        getpsr  r3, psr")
        e("        sto     r3, r0, res")
        e("        %s r1, r1" % random.choice(["mulstep", "divstep"]))   # rd and rs the same, forwarded
        e("        mov     r4, r1")
        e("        %s r4, r2, 3" % k)                                   # source with an imm: read in EA
        e("        cmp     r1, r2")
        e("        z.mulstep r5, r2")
        e("        nz.divstep r6, r2")
    e("")
    e("        # full multiplies: r7 := r9 * r8")
    for i in range(25):
        const(9, random.choice(vals))
        const(8, random.choice(vals))
        e("        mov     r7, r0")
        for _ in range(32):
            e("        add     r9, r9")
            e("        mulstep r7, r8")
        e("        sto     r7, r0, res")
    e("")
    e("        # full unsigned divides: r1 := r1 / r2, r3 := the remainder")
    for i in range(25):
        const(1, random.randint(0, 2**32 - 1))
        const(2, random.choice([1, 3, 10, 100, 0xFFFF, random.randint(1, 2**31), random.randint(2**31, 2**32 - 1)]))
        e("        mov     r3, r0")
        e("        add     r0, r0")
        for _ in range(32):
            e("        rol     r1, r1")
            e("        divstep r3, r2")
        e("        rol     r1, r1")
        e("        sto     r1, r0, res")
        e("        sto     r3, r0, res")
    e("")
    e("        halt    r0, r0, 0x99")
    e("")
    e("        # data")
    e("res: WORD 0")
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'haz_steps.s')
    with open(out, 'w') as f:
        f.write("\n".join(L) + "\n")

if __name__ == '__main__':
    main()
