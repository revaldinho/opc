#!/usr/bin/env python3
'''
gen_hazards.py - write the directed pipeline hazard tests for opc7h

  gen_hazards.py [outdir]

Writes haz_raw.s, haz_flags.s, haz_jump.s, haz_misc.s and haz_int.s (default: the
directory of this script). The tests print nothing and just halt: they are
checked instruction by instruction against opc7emu.py with
../trace_compare.py (make hazards in ..), so every register and flag value on
the way is compared. Each case is written out in full, so the .s files read
as plain straight-line code.

  haz_raw    register dependencies at distance d = 1, 2, 3 (d-1 independent
             fillers between producer and consumer), producer ALU or load,
             through the source or the destination, for ALU, load/store
             address, store data and jump target consumers, imm 0 and not 0
  haz_flags  every predicate after cmp, scmp, sub, add, ror and putpsr at
             d = 1, 2, 3 (fillers that leave the flags alone), both outcomes;
             predicated jumps, loads and stores
  haz_int    software interrupts around early jumps, and a jump-heavy loop that
             int_check.sh also runs under random hardware interrupts
  haz_jump   mov/add/sub pc with immediate and register targets, jsr/ljsr,
             returns through just-loaded registers, jumps to jumps, use of
             registers and flags straight after a jump; trap instructions
             after every jump catch a pipeline that fails to cancel them
  haz_misc   r15 as a source, writes to r0, store then load to the same
             address, putpsr/getpsr, movt/bperm/not dependencies, scmp with
             overflow, ror/rol/asr/lsr with the carry set
'''
import os, sys

class Prog:
    def __init__(self, title, vector=None):
        self.lines = ['        # %s - generated by gen_hazards.py, do not edit' % title, '']
        if vector:   # the interrupt vector is at address 2
            self.lines += ['        mov     pc, r0, START', '        mov     r0, r0', '        mov     pc, r0, ' + vector, 'START:']
        self.lines += ['        # clear r1-r14 first: ALU instructions read their destination']
        self.lines += ['        mov     r%d, r0, 0' % r for r in range(1, 15)]
        self.data = []
        self.n = 0
    def label(self, stem='L'):
        self.n += 1
        return '%s%d' % (stem, self.n)
    def __call__(self, *ins):
        for i in ins:
            self.lines.append(('' if i.endswith(':') else '        ') + i)
    def comment(self, text):
        self.lines += ['', '        # ' + text]
    def word(self, label, value):
        self.data.append('%s: WORD 0x%08X' % (label, value & 0xFFFFFFFF))
    def const(self, reg, value):
        '''load a 32 bit constant with mov + movt'''
        value &= 0xFFFFFFFF
        lo, hi = value & 0xFFFF, value >> 16
        sx = lambda v: v - 0x10000 if v & 0x8000 else v
        self('mov     r%d, r0, %d' % (reg, sx(lo)), 'movt    r%d, r0, %d' % (reg, sx(hi)))
    def trap(self):
        '''instructions a jump must skip'''
        self('mov     r12, r0, 0x0BAD', 'add     r12, r0, 0x0BAD', 'mov     r11, r0, 0x0BAD')
    def write(self, path):
        with open(path, 'w') as f:
            f.write('\n'.join(self.lines + ['', '        halt    r0, r0, 0x99', '', '        # data'] +
                              self.data + ['scratch: WORD 0', '']) + '\n')

def fill(p, k, flags_safe=False):
    '''k independent filler instructions (registers r8-r10 only)'''
    for j in range(k):
        p('sto     r0, r0, scratch' if flags_safe else 'mov     r%d, r0, %d' % (8 + j % 3, 0x111 * (j + 1)))

def haz_raw():
    p = Prog('haz_raw.s: register dependencies')
    p.word('vec', 0)
    for k in range(1, 9):
        p.word('vec%d' % k, 0x1000 * k + k)
    p.word('pval', 0x00012345)            # a value to load
    p.word('pvec', 0)                     # patched below: address of vec4
    p('mov     r2, r0, vec4', 'sto     r2, r0, pvec')
    for d in (1, 2, 3):
        for prod in ('alu', 'load'):
            # producers of a plain value into r1
            pv = (['add     r1, r3, 0x0123'] if prod == 'alu' else ['ld      r1, r0, pval'])
            # producers of an address into r1 (the address of vec4)
            pa = (['mov     r1, r0, vec4'] if prod == 'alu' else ['ld      r1, r0, pvec'])
            cases = [
                ('source, ALU, imm 0',      pv, ['mov     r4, r1']),
                ('source, ALU, imm != 0',   pv, ['add     r4, r1, 0x0077']),
                ('source, xor, imm != 0',   pv, ['xor     r4, r1, 0x5A5A']),
                ('dest, ALU',               pv, ['add     r1, r5, 0x0011']),
                ('dest, and/or',            pv, ['or      r1, r5', 'and     r1, r0, 0x7FFF']),
                ('dest, movt',              pv, ['movt    r1, r0, 0x0042']),
                ('dest and source',         pv, ['add     r1, r1']),
                ('load address, imm 0',     pa, ['ld      r4, r1']),
                ('load address, imm != 0',  pa, ['ld      r4, r1, 2']),
                ('load address, negative',  pa, ['ld      r4, r1, -2']),
                ('store address, imm 0',    pa, ['sto     r5, r1', 'ld      r4, r0, vec4']),
                ('store address, imm != 0', pa, ['sto     r5, r1, 1', 'ld      r4, r0, vec5']),
                ('store data',              pv, ['sto     r1, r0, scratch', 'ld      r4, r0, scratch']),
                ('lld/lsto data and address', pa, ['lsto    r1, scratch', 'lld     r4, scratch', 'ld      r6, r4, 1']),
            ]
            for name, prodi, cons in cases:
                p.comment('d=%d, %s producer, %s' % (d, prod, name))
                p('mov     r3, r0, %d' % (0x200 + d), 'mov     r5, r0, %d' % (0x300 + d))
                p(*prodi)
                fill(p, d - 1)
                p(*cons)
            # jump target in a register
            p.comment('d=%d, %s producer, jump target in the source' % (d, prod))
            t = p.label('T')
            if prod == 'alu':
                p('mov     r1, r0, %s' % t)
            else:
                p.word('p' + t, 0)
                p('mov     r2, r0, %s' % t, 'sto     r2, r0, p%s' % t, 'ld      r1, r0, p%s' % t)
            fill(p, d - 1)
            p('mov     pc, r1')
            p.trap()
            p(t + ':', 'mov     r4, r1')
        # chains: each instruction uses the one before
        p.comment('d=%d chain of dependent ALU and load instructions' % d)
        p('mov     r1, r0, 1')
        for j in range(4):
            p('add     r1, r1, %d' % (j + 1))
            fill(p, d - 1)
        p('mov     r2, r0, vec1')
        for j in range(3):
            p('add     r2, r2, 1')
            fill(p, d - 1)
            p('ld      r3, r2')
            fill(p, d - 1)
            p('add     r4, r3, 1')
    return p

PREDS = ('z', 'nz', 'c', 'nc', 'mi', 'pl')

def haz_flags():
    p = Prog('haz_flags.s: flag predicates')
    setters = [
        ('cmp equal',          lambda: p.const(1, 5) or p.const(2, 5), 'cmp     r1, r2'),
        ('cmp less',           lambda: p.const(1, 3) or p.const(2, 9), 'cmp     r1, r2'),
        ('cmp greater',        lambda: p.const(1, 9) or p.const(2, 3), 'cmp     r1, r2'),
        ('cmp immediate',      lambda: p.const(1, 0x40), 'cmp     r1, r0, 0x40'),
        ('scmp less signed',   lambda: p.const(1, -2) or p.const(2, 1), 'scmp    r1, r2'),
        ('scmp overflow',      lambda: p.const(1, 0x80000000) or p.const(2, 1), 'scmp    r1, r2'),
        ('scmp overflow 2',    lambda: p.const(1, 0x7FFFFFFF) or p.const(2, -1), 'scmp    r1, r2'),
        ('sub to zero',        lambda: p.const(1, 7), 'sub     r1, r0, 7'),
        ('add with carry out', lambda: p.const(1, 0xFFFFFFFF), 'add     r1, r0, 1'),
        ('add negative',       lambda: p.const(1, 0x7FFFFFFF), 'add     r1, r0, 1'),
        ('ror carry out',      lambda: p.const(1, 3), 'ror     r1, r1'),
        ('mov zero',           lambda: p.const(1, 9), 'mov     r1, r0'),
        ('ld negative',        lambda: None, 'ld      r1, r0, negw'),
        ('putpsr',             lambda: p.const(1, 0x80000007), 'putpsr  r0, r1'),
    ]
    p.word('negw', 0x80000000)
    for d in (1, 2, 3):
        for name, setup, ins in setters:
            for pr in PREDS:
                p.comment('d=%d after %s: %s. mov, %s. add, %s. jump' % (d, name, pr, pr, pr))
                setup()
                p('mov     r6, r0, 0x66')
                p(ins)
                fill(p, d - 1, flags_safe=True)
                p('%s.mov  r6, r0, 0x0111' % pr)
                t = p.label('F')
                p('sto     r0, r0, scratch')
                # predicated jump straight after the flag setter
                setup()
                p(ins)
                fill(p, d - 1, flags_safe=True)
                p('%s.mov  pc, r0, %s' % (pr, t))
                p('mov     r7, r0, 0x0777')       # executed only if the jump is not taken
                p(t + ':', 'getpsr  r9, r0')
    p.comment('predicated loads and stores, both outcomes')
    p.word('pw', 0x0000ABCD)
    for pr in PREDS:
        p.const(1, 5)
        p('cmp     r1, r0, 5', '%s.ld   r2, r0, pw' % pr, '%s.sto  r1, r0, scratch' % pr,
          'ld      r3, r0, scratch', 'sto     r0, r0, scratch')
        p('cmp     r1, r0, 6', '%s.ld   r4, r0, pw' % pr, '%s.sto  r1, r0, scratch' % pr,
          'ld      r5, r0, scratch', 'sto     r0, r0, scratch')
    p.comment('a counted loop with a predicated backward jump')
    p('mov     r1, r0, 5', 'mov     r2, r0, 0')
    p('LOOP1:', 'add     r2, r1', 'sub     r1, r0, 1', 'nz.mov  pc, r0, LOOP1', 'mov     r3, r2')
    p.comment('predicted jumps (immediate, backward): every predicate, both outcomes, d = 1, 2, 3 after the flags')
    for d in (1, 2, 3):
        for pr in PREDS:
            for v in (5, 6):
                b, o, e = p.label('B'), p.label('O'), p.label('E')
                p('mov     pc, r0, %s' % o)
                p(b + ':', 'mov     r7, r0, 0x0777', 'mov     pc, r0, %s' % e)
                p(o + ':', 'mov     r1, r0, %d' % v, 'mov     r7, r0, 0', 'mov     r6, r0, 0', 'cmp     r1, r0, 5')
                fill(p, d - 1, flags_safe=True)
                p('%s.mov  pc, r0, %s' % (pr, b), 'mov     r6, r0, 0x0666')
                p(e + ':', 'getpsr  r9, r0')
    return p

def haz_jump():
    p = Prog('haz_jump.s: jumps')
    t = p.label('J')
    p.comment('unpredicated mov pc to an immediate'); p('mov     pc, r0, %s' % t); p.trap(); p(t + ':')
    t, t2, jx = p.label('J'), p.label('J'), p.label('JX')
    p.comment('jumps forward, back and forward again')
    p('mov     r1, r0, 0', 'mov     pc, r0, %s' % t2)
    p(t + ':', 'add     r1, r0, 0x0222', 'mov     pc, r0, %s' % jx)
    p(t2 + ':', 'mov     pc, r0, %s' % t)
    p.trap()
    p(jx + ':', 'mov     r2, r1')
    p.comment('jump to a jump to a jump')
    a, b, c = p.label('A'), p.label('B'), p.label('C')
    p('mov     pc, r0, %s' % a); p.trap()
    p(a + ':', 'mov     pc, r0, %s' % b); p.trap()
    p(b + ':', 'mov     pc, r0, %s' % c); p.trap()
    p(c + ':', 'mov     r3, r0, 0x0333')
    p.comment('registers and flags computed just before a jump, used at the target')
    t = p.label('J')
    p('mov     r4, r0, 0x0444', 'cmp     r4, r0, 0x0444', 'mov     pc, r0, %s' % t); p.trap()
    p(t + ':', 'add     r5, r4, 1', 'z.mov   r6, r0, 0x0666', 'nz.mov  r6, r0, 0x0BAD')
    p.comment('jsr and ljsr, link register used at once, return through it')
    s1, s2 = 'SUB1', 'SUB2'
    p('jsr     r13, r0, %s' % s1, 'mov     r7, r13', 'ljsr    r13, %s' % s2, 'mov     r8, r13')
    p.comment('return through a just-loaded register, and through a computed one')
    s3 = 'SUB3'
    p('jsr     r13, r0, %s' % s3, 'mov     r9, r0, 0x0999')
    p.comment('jump target in a register computed one instruction before')
    t = p.label('J')
    p('mov     r1, r0, %s' % t, 'mov     pc, r1'); p.trap(); p(t + ':', 'mov     r2, r1')
    t = p.label('J')
    p('mov     r1, r0, %s - 4' % t, 'mov     pc, r1, 4'); p.trap(); p(t + ':', 'mov     r3, r1')   # register + offset target
    p.comment('predicated jump not taken, then taken, in a row')
    t = p.label('J')
    p('mov     r1, r0, 1', 'cmp     r1, r0, 2', 'z.mov   pc, r0, %s' % t, 'nz.mov  pc, r0, %s' % t); p.trap()
    p(t + ':', 'mov     r4, r0, 0x0444')
    p.comment('a jump in the shadow of a taken jump must not happen')
    t, u = p.label('J'), p.label('U')
    p('mov     pc, r0, %s' % t, 'mov     pc, r0, %s' % u, 'mov     r12, r0, 0x0BAD')
    p(u + ':', 'mov     r12, r0, 0x0BAD', 'mov     r11, r0, 0x0BAD')
    p(t + ':', 'mov     r5, r0, 0x0555')
    p.comment('early jumps (unpredicated, taken from EA) in the shadow of an older jump: they must not count')
    p.word('flagw', 0)
    t, w = p.label('J'), p.label('W')
    p('mov     r7, r0, 0x0777', 'cmp     r7, r7', 'z.mov   pc, r0, %s' % t, 'mov     pc, r0, %s' % w, 'mov     r12, r0, 0x0BAD')
    p(w + ':', 'sto     r7, r0, flagw', 'mov     r12, r0, 0x0BAD', 'mov     r11, r0, 0x0BAD')
    p(t + ':', 'ld      r6, r0, flagw', 'add     r5, r6, 1')
    t, w = p.label('J'), p.label('W')
    p('cmp     r7, r7', 'z.mov   pc, r0, %s' % t, 'jsr     r10, r0, %s' % w, 'mov     r12, r0, 0x0BAD')
    p(w + ':', 'sto     r7, r0, flagw', 'mov     r12, r0, 0x0BAD')
    p(t + ':', 'ld      r6, r0, flagw', 'mov     r4, r10')
    p.comment('an early jump behind a predicated jump that is not taken, or behind a loaded or computed jump')
    t, u = p.label('J'), p.label('U')
    p('cmp     r7, r7', 'nz.mov  pc, r0, %s' % u, 'mov     pc, r0, %s' % t)
    p(u + ':'); p.trap()
    p(t + ':', 'mov     r1, r0, 0x0111')
    t, u, w = p.label('J'), p.label('U'), p.label('W')
    p.word('tgt', 0)
    p('mov     r2, r0, %s' % t, 'sto     r2, r0, tgt', 'ld      pc, r0, tgt', 'mov     pc, r0, %s' % w); p.trap()
    p(w + ':'); p.trap()
    p(t + ':', 'mov     r3, r0, 0x0333')
    p.comment('stores, out, in and loads at the target of an early jump and in its shadow')
    # opc7emu.py's in reads stdin (0 here), the testbench's reads what out wrote: port 0x200 holds 0 for both
    p('out     r0, r0, 0x200')
    for first in ('sto     r7, r0, flagw', 'out     r7, r0, 0x100', 'in      r6, r0, 0x200', 'ld      r6, r0, flagw'):
        t = p.label('J')
        p('add     r7, r0, 1', 'mov     pc, r0, %s' % t, 'sto     r0, r0, flagw', 'out     r0, r0, 0x100'); p.trap()
        p(t + ':', first, 'ld      r8, r0, flagw', 'mov     r9, r6')
    p.comment('a store, out or in straight behind a taken predicated jump must not happen')
    for first in ('sto     r7, r0, flagw', 'out     r7, r0, 0x200'):
        t = p.label('J')
        p('cmp     r7, r7', 'z.mov   pc, r0, %s' % t, first, 'mov     r12, r0, 0x0BAD')
        p(t + ':', 'ld      r6, r0, flagw', 'in      r5, r0, 0x200', 'mov     r4, r6')
    t = p.label('J')
    p('mov     r2, r0, %s' % t, 'cmp     r2, r2', 'z.mov   pc, r2', 'mov     r3, r0, 1', 'sto     r3, r0, flagw', 'mov     r12, r0, 0x0BAD')
    p(t + ':', 'ld      r6, r0, flagw')
    p.comment('a load straight behind a jump taken in EX must not happen, also while its reply is slow (dwait)')
    p('mov     r7, r0, 0x0777', 'sto     r7, r0, flagw')
    for first in ('ld      r6, r0, flagw', 'lld     r6, flagw'):
        for jump in ('z.mov   pc, r0, %s', 'z.mov   pc, r2'):
            t = p.label('J')
            p('mov     r2, r0, %s' % t, 'mov     r6, r0, 0x0666', 'cmp     r7, r7', jump % t if '%' in jump else jump, first, 'mov     r12, r0, 0x0BAD')
            p(t + ':', 'mov     r4, r6')
    p.comment('r15 and the link register as the source of the jump')
    t = p.label('J')
    p('mov     pc, pc, 3'); p.trap(); p('mov     r1, r0, 0x0111')
    p('mov     r1, r0, %s' % t, 'jsr     r1, r1'); p.trap(); p(t + ':', 'mov     r2, r1')
    t = p.label('J')
    p('jsr     r0, r0, %s' % t); p.trap(); p(t + ':', 'add     r3, r0, 1')
    p.comment('a store that needs the link of the jsr before it, and back-to-back early jumps at a target')
    t, u = p.label('J'), p.label('U')
    p('jsr     r13, r0, %s' % t, 'mov     pc, r0, %s' % u); p.trap()
    p(t + ':', 'sto     r13, r0, flagw', 'ld      r5, r0, flagw', 'mov     pc, r5'); p.trap()
    p(u + ':', 'mov     r6, r5')
    p.comment('predicted jumps (immediate, backward): each form taken once, then not taken, so the second is mispredicted')
    for form in ('nz.mov  pc, r0, %s', 'nz.lmov pc, %s', 'nz.mov  pc, pc, -3', 'nz.jsr  r13, r0, %s', 'nz.ljsr r13, %s'):
        b = p.label('B')
        p('mov     r1, r0, 2', 'mov     r2, r0, 0', 'mov     r13, r0, 0')
        p(b + ':', 'add     r2, r2, 1', 'sub     r1, r0, 1', form % b if '%' in form else form, 'mov     r3, r13', 'add     r4, r2, 1')
    p.comment('a mispredicted jump: nothing at its target may happen, whatever is there')
    p('out     r0, r0, 0x200')
    for first in ('sto     r7, r0, flagw', 'out     r7, r0, 0x200', 'in      r6, r0, 0x200', 'halt    r0, r0, 0x55',
                  'putpsr  r0, r0, 0x18', 'rti     pc, pc', 'mov     pc, r0, DONE', 'jsr     r13, r0, DONE', 'z.mov   pc, r0, DONE'):
        b, o = p.label('B'), p.label('O')
        p('mov     pc, r0, %s' % o)
        p(b + ':', first); p.trap()
        p(o + ':', 'sto     r0, r0, flagw', 'mov     r7, r0, 0x0777', 'cmp     r7, r7', 'nz.mov  pc, r0, %s' % b,
          'ld      r6, r0, flagw', 'in      r5, r0, 0x200', 'mov     r4, r6')
    p.comment('a store two behind the target; a jump to itself; two mispredicted in a row; one taken, the next in its shadow')
    b, o = p.label('B'), p.label('O')
    p('mov     pc, r0, %s' % o)
    p(b + ':', 'mov     r12, r0, 0x0BAD', 'sto     r7, r0, flagw'); p.trap()
    p(o + ':', 'cmp     r7, r7', 'nz.mov  pc, r0, %s' % b, 'nz.mov  pc, r0, %s' % b, 'ld      r6, r0, flagw')
    t = p.label('B')
    p('cmp     r7, r7', t + ':', 'nz.mov  pc, r0, %s' % t, 'mov     r1, r2')
    b, o, u = p.label('B'), p.label('O'), p.label('U')
    p('mov     pc, r0, %s' % o)
    p(b + ':', 'mov     r3, r0, 0x0333', 'mov     pc, r0, %s' % u)
    p(o + ':', 'cmp     r7, r7', 'z.mov   pc, r0, %s' % b, 'z.mov   pc, r0, %s' % o, 'sto     r7, r0, flagw'); p.trap()
    p(u + ':', 'ld      r6, r0, flagw')
    p.comment('a mispredicted jsr or ljsr must not write the link')
    b, o = p.label('B'), p.label('O')
    p('mov     pc, r0, %s' % o)
    p(b + ':'); p.trap()
    p(o + ':', 'mov     r13, r0, 0x0123', 'cmp     r7, r7', 'nz.jsr  r13, r0, %s' % b, 'mov     r3, r13', 'cmp     r7, r7', 'nz.ljsr r13, %s' % b, 'mov     r4, r13')
    p.comment('a predicted jump in the shadow of a jump taken in EX, which has to win')
    b, o, u = p.label('B'), p.label('O'), p.label('U')
    p('mov     pc, r0, %s' % o)
    p(b + ':'); p.trap()
    p(o + ':', 'mov     r2, r0, %s' % u, 'cmp     r2, r2', 'z.mov   pc, r2', 'z.mov   pc, r0, %s' % b); p.trap()
    p(u + ':', 'mov     r4, r2')
    p.comment('predicate 0., never execute (001): nothing may change, flags included. The backward jumps are predicted taken, so they must also recover')
    p('out     r0, r0, 0x200', 'sto     r0, r0, flagw', 'mov     r1, r0, flagw', 'mov     r7, r0, 0x0777', 'mov     r6, r0, 0x0666', 'mov     r13, r0, 0x0123')
    for never in ('mov     r12, r0, 0x0BAD', 'add     r12, r0, 1', 'sto     r7, r1', 'out     r7, r0, 0x200', 'in      r6, r0, 0x200',
                  'putpsr  r0, r0, 0x18', 'halt    r0, r0, 0x55', 'rti     pc, pc', 'mov     pc, pc, 1', 'mov     pc, pc, -2', 'mov     pc, r0, 0',
                  'lmov    pc, 0', 'jsr     r13, pc, 1', 'jsr     r13, r0, 0', 'ljsr    r13, 0'):
        p('cmp     r7, r7', '0.' + never, 'getpsr  r2, r0', 'mov     r3, r13', 'mov     r4, r6', 'ld      r5, r0, flagw', 'in      r8, r0, 0x200')
    p.comment('done: skip the subroutines')
    p('mov     pc, r0, DONE')
    p(s1 + ':', 'add     r10, r13, 1', 'mov     pc, r13'); p.trap()
    p(s2 + ':', 'add     r10, r13, 2', 'mov     pc, r13, 0'); p.trap()
    p.word('saved', 0)
    p(s3 + ':', 'sto     r13, r0, saved', 'mov     r13, r0, 0', 'ld      r13, r0, saved', 'mov     pc, r13'); p.trap()
    p('DONE:', 'mov     r6, r0, 0x0D0E')
    return p

def haz_misc():
    p = Prog('haz_misc.s: r15, r0, memory, psr and the rarer operations')
    p.comment('r15 as a source: the address of the next instruction')
    p('mov     r1, pc', 'add     r2, pc, 5', 'ld      r3, pc, 1', 'mov     pc, r0, M1', 'WORD 0x00C0FFEE')
    p('M1:', 'add     r4, r3, 1')
    p.comment('writes to r0 must leave it zero')
    p('mov     r0, r0, 5', 'add     r1, r0', 'add     r0, r0, 7', 'mov     r2, r0, 3', 'ld      r0, r0, mw', 'add     r3, r0, 1')
    p.word('mw', 0x12345678)
    p.comment('store then load to the same address, d = 1, 2, 3, and load then store')
    p.word('sl', 0)
    for d in (1, 2, 3):
        p('mov     r1, r0, %d' % (0x100 * d), 'sto     r1, r0, sl')
        fill(p, d - 1)
        p('ld      r2, r0, sl')
        p('add     r1, r2, 1', 'sto     r1, r0, sl', 'ld      r3, r0, sl', 'sto     r3, r0, sl', 'ld      r4, r0, sl')
    p.comment('putpsr and getpsr, with dependencies on both sides')
    for v in (0x00000000, 0x00000005, 0x80000002, 0x00000007):
        p.const(1, v)
        p('putpsr  r0, r1', 'getpsr  r2, r0', 'mi.mov  r3, r0, 1', 'z.mov   r3, r0, 2', 'c.mov   r3, r0, 4', 'mov     r4, r2')
    p.comment('movt, bperm and not after a dependent instruction')
    p.const(1, 0x11223344)
    p('movt    r1, r0, 0x5566', 'bperm   r2, r1, 0x0123', 'not     r3, r2', 'bperm   r4, r3, 0x3210', 'not     r5, r4, 1')
    p.comment('bperm with imm 0 straight after its source is written: the source is permuted, so it cannot be forwarded late')
    for d in (1, 2):
        p.const(1, 0x11223344)
        fill(p, d - 1)
        p('bperm   r2, r1, 0', 'add     r3, r2, 1')
    p.comment('cmp and scmp with r15 as destination compare and do not jump; with add pc, the flags stay, V included')
    t, u = p.label('M'), p.label('M')
    p('mov     r1, r0, 0x0100', 'cmp     pc, r1', 'getpsr  r2, r0', 'mov     r5, r0, 1', 'scmp    pc, r1, 4', 'getpsr  r3, r0', 'mov     r6, r0, 2')
    p.const(1, 0x7FFFFFFF)
    p('add     r1, r0, 1', 'getpsr  r2, r0', 'add     pc, r0, 1', 'mov     r12, r0, 0x0BAD', 'getpsr  r3, r0')
    p.const(1, 0x7FFFFFFF)
    p('mov     r2, r0, 0', 'add     r1, r0, 1', 'sub     pc, r0, -1', 'mov     r12, r0, 0x0BAD', 'getpsr  r4, r0')
    p.comment('scmp with overflow, both ways')
    for a, b in ((0x80000000, 1), (1, 0x80000000), (0x7FFFFFFF, -1), (-1, 0x7FFFFFFF), (0x80000000, 0x7FFFFFFF)):
        p.const(1, a); p.const(2, b)
        p('scmp    r1, r2', 'getpsr  r3, r0', 'mi.mov  r4, r0, 1', 'pl.mov  r4, r0, 2')
    p.comment('ror, rol, asr, lsr with the carry set and clear')
    for cin in (1, 0):
        for opn in ('ror', 'rol', 'asr', 'lsr'):
            p.const(1, 0xFFFFFFFF)
            p('add     r1, r0, %d' % cin)       # carry out = cin
            p.const(2, 0x80000001)
            p('%-7s r3, r2' % opn, 'getpsr  r4, r0', '%-7s r5, r3' % opn, 'getpsr  r6, r0')
    return p

def haz_int():
    '''Also the program for the hardware interrupt check (int_check.sh): r11 and r14 belong to the
    handler, and r1 depends on the order and number of everything the main loop does and is
    stored as it goes, so a lost, repeated or misdirected instruction shows up.'''
    p = Prog('haz_int.s: software interrupts, and a main loop for hardware interrupts', 'HANDLER')
    p.word('buf', 0); p.word('tgt', 0)
    def mix(k):
        p('add     r1, r1, %d' % k)
    def wrong():
        p('add     r1, r0, 0x0BAD', 'sto     r1, r0, buf', 'mov     r12, r0, 0x0BAD')
    p('mov     r2, r0, 48', 'mov     r1, r0, 1', 'out     r0, r0, 0x200')   # port 0x200: see haz_jump
    p.comment('software interrupts around early jumps; EI stays set')
    p('putpsr  r0, r0, 8')
    t, u = p.label('J'), p.label('U')
    p('putpsr  r0, r0, 0x18', 'mov     pc, r0, %s' % t); wrong()
    p(t + ':', 'mov     pc, r0, %s' % u); wrong()
    p(u + ':', 'putpsr  r0, r0, 0x28', 'mov     r3, r14')
    p.comment('a store straight behind a software interrupt happens after the handler, which reads it into r11')
    p('mov     r3, r0, 5', 'sto     r0, r0, sv', 'putpsr  r0, r0, 0x18', 'sto     r3, r0, sv', 'mov     r4, r11')
    p.word('sv', 0)
    p.comment('main loop')
    labels = [p.label('M') for _ in range(9)]
    a, b, c, d, e, f, g, h, i = labels
    p('LOOP:'); mix(3)
    p('lmov    pc, %s' % a); wrong()
    p(a + ':'); mix(5)
    p('mov     r3, r0, %s' % b, 'mov     pc, r3'); wrong()
    p(b + ':', 'sto     r1, r0, buf', 'ld      r4, r0, buf', 'add     r1, r4, 7')
    k = p.label('K')    # a predicted jump, right once and wrong once, with a store at its target
    p('mov     r3, r0, 2', k + ':', 'sto     r1, r0, buf', 'add     r1, r1, 21', 'sub     r3, r0, 1', 'nz.mov  pc, r0, %s' % k, 'add     r1, r1, 23')
    p('jsr     r13, r0, SUB', 'add     r1, r1, 9')
    p('sto     r1, r0, buf', 'cmp     r1, r1', 'z.mov   pc, r0, %s' % c, 'mov     pc, r0, %s' % d); wrong()
    p(d + ':'); wrong()
    p(c + ':', 'out     r1, r0, 0x100', 'in      r5, r0, 0x200', 'add     r1, r1, 11')
    p('mov     r3, r0, %s' % e, 'sto     r3, r0, tgt', 'ld      r3, r0, tgt', 'mov     pc, r3, 0'); wrong()
    p(e + ':', 'add     r6, r0, -1', 'add     r6, r0, 1', 'c.add   r1, r1, 13', 'nc.add  r1, r1, 15')
    p('mov     r3, r0, %s - 4' % f, 'mov     pc, r3, 4', 'sto     r0, r0, buf'); wrong()
    p(f + ':', 'sto     r1, r0, buf', 'lmov    pc, %s' % g); wrong()
    p(g + ':', 'mov     pc, r0, %s' % h); wrong()
    p(h + ':', 'ljsr    r13, SUB', 'out     r1, r0, 0x101', 'mov     r3, r2', 'and     r3, r0, 3', 'z.mov   pc, r0, %s' % i); mix(17)
    p(i + ':', 'mov     r7, r0, LOOP', 'sub     r2, r0, 1', 'sto     r1, r0, buf', 'nz.mov  pc, r7')
    p('sto     r1, r0, buf', 'mov     pc, r0, DONE')
    p('SUB:', 'sto     r13, r0, tgt', 'add     r1, r1, 19', 'ld      r13, r0, tgt', 'mov     pc, r13'); wrong()
    p.comment('the handler only touches r11 and r14; the early jump after rti must not count')
    p('HANDLER:', 'add     r14, r0, 1', 'ld      r11, r0, sv', 'mov     pc, r0, H2'); wrong()
    p('H2:', 'rti     pc, pc', 'mov     pc, r0, HBAD')
    p('HBAD:'); wrong()
    p('DONE:', 'mov     r6, r0, 0x0D0E')
    return p

